#!/usr/bin/env node
/*
 * Generates the copy tables in docs/design/copy.md from design/prototypes/assets/copy.js.
 *   node design/prototypes/check/copy-table.cjs           print the tables
 *   node design/prototypes/check/copy-table.cjs --write   rewrite the generated block in copy.md
 * check.cjs fails if copy.md is out of date.
 */
"use strict";
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../../..");
const COPY_MD = path.join(ROOT, "docs/design/copy.md");
const START = "<!-- copy-table:start (generated by design/prototypes/check/copy-table.cjs; edit copy.js, not this block) -->";
const END = "<!-- copy-table:end -->";

function load() {
  delete require.cache[require.resolve("../assets/copy.js")];
  return require("../assets/copy.js");
}

const cell = (s) => (s ? String(s).replace(/\|/g, "\\|").replace(/\n/g, " ") : "—");

function table(entries) {
  const head =
    "| Key | Surface | Title | Body | Primary | Secondary | Announce | T10 code | Notes |\n" +
    "|---|---|---|---|---|---|---|---|---|\n";
  return head + entries.map(([k, c]) =>
    `| \`${k}\` | ${cell(c.surface)} | ${cell(c.title)} | ${cell(c.body)} | ${cell(c.primary)} | ${cell(c.secondary)} | ${cell(c.announce)} | ${cell(c.t10)} | ${cell(c.notes)} |`
  ).join("\n") + "\n";
}

function generate() {
  const { COPY } = load();
  const all = Object.entries(COPY);
  const sections = [
    ["Detection states (D-008)", "detection-state"],
    ["Scan dialog states", "scan-state"],
    ["Error codes (contract `code`, RFC 9457)", "error"],
    ["Tray / menu-bar agent", "tray"],
  ];
  let out = START + "\n\n";
  for (const [title, kind] of sections) {
    out += `### ${title}\n\n` + table(all.filter(([, c]) => c.kind === kind && c.t10 !== "added")) + "\n";
  }
  out += "### Codes added by T10\n\n" +
    "Codes the T10 contract added (`api/CONTRACT.md` §9, hand-off \"For T05\"). Copy written in T05 fix r1 " +
    "(`t10: \"added\"`). `host-denied` and `token-invalid` have no copy (unreachable or silent); `invalid-request` " +
    "and `invalid-state` use `unknown`.\n\n" +
    table(all.filter(([, c]) => c.t10 === "added")) + "\n";
  out += "\n" + END;
  return out;
}

function currentBlock() {
  const md = fs.readFileSync(COPY_MD, "utf8");
  const a = md.indexOf(START), b = md.indexOf(END);
  if (a < 0 || b < 0) return null;
  return md.slice(a, b + END.length);
}

function write() {
  const md = fs.readFileSync(COPY_MD, "utf8");
  const block = currentBlock();
  if (!block) throw new Error("copy.md is missing the copy-table markers");
  fs.writeFileSync(COPY_MD, md.replace(block, generate()));
}

module.exports = { generate, currentBlock, load };

if (require.main === module) {
  if (process.argv.includes("--write")) { write(); console.log("Updated " + path.relative(ROOT, COPY_MD)); }
  else process.stdout.write(generate() + "\n");
}
