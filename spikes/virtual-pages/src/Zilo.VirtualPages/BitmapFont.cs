    public static string[] Glyph(char c)
    {
        c = char.ToUpperInvariant(c);
        return Glyphs.TryGetValue(c, out var g) ? g : Glyphs['?'];
    }

    /// <summary>Width in pixels of <paramref name="text"/> at integer <paramref name="scale"/> (no trailing gap).</summary>
    public static int MeasureWidth(string text, int scale) =>
        text.Length == 0 ? 0 : (text.Length * CellWidth - 1) * scale;

    /// <summary>Largest integer scale (≥ 1) so that the text fits in the box.</summary>
    public static int FitScale(string text, int maxWidthPx, int maxHeightPx)
    {
        var byHeight = maxHeightPx / GlyphHeight;
        var byWidth = text.Length == 0 ? byHeight : maxWidthPx / (text.Length * CellWidth - 1);
        return Math.Max(1, Math.Min(byHeight, byWidth));
    }

    public static void Draw(Raster r, string text, int x, int y, int scale, Rgb color)
    {
        for (var i = 0; i < text.Length; i++)
        {
            var g = Glyph(text[i]);
            var gx = x + i * CellWidth * scale;
            for (var row = 0; row < GlyphHeight; row++)
            for (var col = 0; col < GlyphWidth; col++)
                if (g[row][col] == '#')
                    r.FillRect(gx + col * scale, y + row * scale, scale, scale, color);
        }
    }
