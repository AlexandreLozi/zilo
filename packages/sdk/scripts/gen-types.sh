#!/usr/bin/env bash
# Regenerates the committed contract artefacts under src/generated/ from api/openapi.yaml, with the
# same pinned tooling as the T10 acceptance check (api/tools/check.sh): openapi-typescript and yaml
# run from a scratch directory outside the repo, so the workspace gains no dependency.
#   src/generated/openapi.ts    types (openapi-typescript)
#   src/generated/openapi.json  the spec as JSON, read by the contract-driven test mock server
#   src/generated/spec-hash.ts  SHA-256 of api/openapi.yaml; a unit test fails when it drifts
set -euo pipefail

OPENAPI_TS=7.13.0 # keep in step with api/tools/check.sh
YAML_PKG=2.8.1    # keep in step with api/tools/check.sh

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
pkg="$(dirname "$here")"
repo="$(cd "$pkg/../.." && pwd)"
spec="$repo/api/openapi.yaml"
out="$pkg/src/generated"
mkdir -p "$out"

scratch="$(mktemp -d "${TMPDIR:-/tmp}/zilo-sdk-gen.XXXXXX")"
trap 'rm -rf "$scratch"' EXIT
(
  cd "$scratch"
  npm init -y >/dev/null
  npm install --silent --no-audit --no-fund --ignore-scripts --save-exact \
    "openapi-typescript@$OPENAPI_TS" "yaml@$YAML_PKG"
  npx --no-install openapi-typescript "$spec" -o types.ts
  node --input-type=module -e '
    import { readFileSync, writeFileSync } from "node:fs";
    import { parse } from "yaml";
    writeFileSync("spec.json", JSON.stringify(parse(readFileSync(process.argv[1], "utf8"))));
  ' "$spec"
)

hash="$(sha256sum "$spec" | cut -d' ' -f1)"
{
  echo "/* eslint-disable */"
  echo "// Generated by packages/sdk/scripts/gen-types.sh (openapi-typescript@$OPENAPI_TS) from"
  echo "// api/openapi.yaml. Do not edit by hand."
  cat "$scratch/types.ts"
} >"$out/openapi.ts"
cp "$scratch/spec.json" "$out/openapi.json"
cat >"$out/spec-hash.ts" <<TS
// Generated by packages/sdk/scripts/gen-types.sh. Do not edit by hand.
/** SHA-256 of api/openapi.yaml when src/generated/ was last regenerated. */
export const SPEC_SHA256 = '$hash';
TS

cd "$repo"
pnpm exec prettier --write --log-level warn "$out"
echo "OK: regenerated $out from $(basename "$spec") ($hash)"
